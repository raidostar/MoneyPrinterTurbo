"""
세로 영상에서 플랫폼 UI 가 덮는 자리.

같은 영상을 유튜브 쇼츠, 인스타 릴스, 스레드에 올린다. 세 곳 다 화면 위에 자기
UI 를 얹는데 덮는 넓이가 다르다. 가장 많이 덮는 쪽에 맞춰 두면 한 벌로 세 곳이
다 된다 — 플랫폼마다 다른 영상을 만드는 것보다, 한 벌을 제일 좁은 안전 영역에
맞추는 편이 관리할 것이 적다.

여기 숫자는 화면 높이에 대한 비율이다. 캔버스 크기가 바뀌어도 같이 움직여야 한다.
"""

# 아래쪽. 인스타 릴스가 캡션, 계정 이름, 음원 표시로 약 310px(1920 기준)을 덮어
# 세 곳 중 가장 넓다. 유튜브 쇼츠는 약 300px, 스레드는 그보다 좁다.
BOTTOM_RATIO = 0.16

# 위쪽. 유튜브 쇼츠가 상단에 검색과 설정을 얹는다. 릴스는 위쪽이 비교적 비어
# 있지만, 여기에 맞춰 두면 어느 쪽에서도 잘리지 않는다.
TOP_RATIO = 0.07

# 오른쪽. 릴스와 쇼츠 모두 좋아요·댓글·공유 버튼을 세로로 세운다.
RIGHT_RATIO = 0.09


def bottom(canvas_height: int) -> int:
    """화면 아래에서 이만큼은 비워 둔다."""
    return int(canvas_height * BOTTOM_RATIO)


def top(canvas_height: int) -> int:
    """화면 위에서 이만큼은 비워 둔다."""
    return int(canvas_height * TOP_RATIO)
